"""井截面取热模型的**网格构造**（``mesh_xz``）.

建模由 ``_well_cross_section.py`` 组装，这里只负责几何 ——
换网格形状时不必碰建模参数。

网格形状
--------

一个**二维近似**下的矩形区域（y 方向只取一层薄壳）。三个方向的范围由参数
``xr`` / ``yr`` / ``zr`` 给定，下表是**函数默认值**：

================  ==========================  ==========================
方向               默认范围                     说明
================  ==========================  ==========================
x                 ``[-0.6, 0.6]``             被 ``jx`` 等分
y                 ``[-0.5, 0.5]``             **只有一层**，厚度 1 m
z                 ``[-1, 1]``                 被 ``jz`` 等分
================  ==========================  ==========================

⚠️ **本包算例用的不是这里的默认范围**：``_well_cross_section.create`` 传入的是
``xr = zr = (-50, 50)``（井周 100 m 见方的剖面），见那里的 ``create`` 文档。

⚠️ **y 方向只有一层是刻意的**：算例是二维的（``cases/case_02.py`` 画的是
x–z 平面），给 y 一个 1 m 的厚度只是为了让它仍是一个三维渗流模型，同时
``tfc.get_x`` / ``tfc.get_z`` 取出的矩阵可以按 ``[jx, jz]`` 重塑。

⚠️ **不做 y 方向加密**：``create_cube`` 的 ``y`` 参数给的是两个节点
（``[-0.5, 0.5]``）而不是 ``linspace``，于是 y 方向只有一层单元 ——
若改成多节点，单元编号与 ``[jx, jz]`` 的重塑关系就不再成立，
``_show.show`` 会画错。
"""

import math

from zmlx import create_cube, linspace


def _nodes(r, count):
    """把「范围」翻译成网格节点序列.

    Args:
        r: 方向范围。长度为 2 的 ``(lo, hi)`` 表示在该区间**等分** ``count`` 段；
            更长的序列则视为**已经是节点位置**（原样返回，``count`` 被忽略）。
        count: 要划分的段数（仅当 ``r`` 是两元组时使用）。

    Returns:
        list[float]: 从小到大排列的节点位置。

    ⚠️ 之所以允许直接给节点序列：非均匀网格（例如井附近加密）只能这样表达，
    两元组 + 均匀分段做不到。

    ⚠️ 段数必须为正：``count <= 0`` 会得到少于两个节点的退化结果，
    ``create_cube`` 内部会断言失败，所以这里先抛 ``ValueError`` 把话说清楚。
    """
    r = tuple(r)
    if len(r) == 2:
        if count <= 0:
            raise ValueError(f"网格段数必须为正，当前为 {count}")
        return linspace(r[0], r[1], count + 1)
    if len(r) < 2:
        raise ValueError(f"范围至少要给两个边界值，当前为 {r}")
    return list(r)


def mesh_xz(*, jx=60, jz=100, xr=(-0.6, 0.6), yr=(-0.5, 0.5), zr=(-1.0, 1.0)):
    """创建算例的矩形网格（**x–z 剖面**，y 方向只有一层）.

    名字里的 ``xz`` 点明这是一张 **x–z 平面上的二维网格**：y 方向只是个薄壳，
    不参与划分。所以 ``mesh_xz(...)`` 得到的 ``[jx, jz]`` 可以直接重塑成
    x–z 图上的二维矩阵（见 ``_show.show``）。

    Args:
        jx: x 方向的网格数量（正整数），范围 ``xr`` 等分为 ``jx`` 段。
        jz: z 方向的网格数量（正整数），范围 ``zr`` 等分为 ``jz`` 段。
        xr: **x 方向的范围**，``(x_min, x_max)`` 或节点序列。给两元组时在其间
            等分 ``jx`` 段；给更长的序列时**直接用这些节点**（此时 ``jx`` 不参与划分，
            以节点数为准）。默认 ``(-0.6, 0.6)``。
        yr: **y 方向的范围**，``(y_min, y_max)``。⚠️ 默认只给两个值，
            于是 y 方向只有**一层**单元（二维近似）；给更多节点会变成多层三维网格，
            ``[jx, jz]`` 的重塑关系随之失效（见下面 Note）。默认 ``(-0.5, 0.5)``。
        zr: **z 方向的范围**，``(z_min, z_max)`` 或节点序列，规则同 ``xr``。默认 ``(-1, 1)``。

    Returns:
        SeepageMesh: 规则六面体网格。

            - 单层 y 时单元数为 ``jx * jz``（实测默认参数得 6000 个单元 / 11840 个面；
              ``jx=8, jz=12`` 得 96 / 172）。
            - 若 ``yr`` 给了 ``n`` 个节点，单元数变为 ``jx * jz * (n - 1)``。

    Note:
        单元按「**先 z 后 x**」的次序编号（z 变化最快）：实测 x 分 4 段、z 分 6 段时，
        前 6 个单元 x 都相同、z 逐个递增，第 7 个才换下一个 x。这正是 ``_show.show``
        里 ``tfc.get_fa(..., shape=[jx, jz])`` 能还原成二维矩阵的前提。

        ⚠️ 改 ``yr`` 的节点数或改范围时，除了上面这条重塑前提，还要注意每个算例自身的
        几何假设（例如 ``_well_cross_section.create`` 里井位是**按 ``xr`` / ``zr`` 范围
        给出的，而不是写死网格坐标）。

    Example:
        >>> mesh_xz().cell_number          # 默认参数：60 x 100
        6000
        >>> mesh_xz(jx=8, jz=12, xr=(0, 1), yr=(0, 1), zr=(0, 2)).cell_number
        96
    """
    x = _nodes(xr, jx)
    y = _nodes(yr, 1)  # y 方向只取一层（两节点），见上面的 Note
    z = _nodes(zr, jz)
    return create_cube(x=x, y=y, z=z)


def equivalent_area(s0, s1):
    """线性变截面通道的**流体阻力等效面积**（数值上等于对数平均面积）.

    假设通道从入口到出口长 ``L``、压降与流速满足 ``dp = dL / s``（``s`` 为流通面积），
    而面积沿程从 ``s0`` **线性**变到 ``s1``。求一个**恒定**面积 ``s_eq``，使这段通道的
    总流动阻力与变截面通道相同，即满足::

        L / s_eq = ∫₀ᴸ dL' / s(L'),    s_eq = (s1 - s0) / ln(s1 / s0)

    也就是 ``s0`` 与 ``s1`` 的**对数平均**（几何平均的极近亲）：
    它不是算术平均 ``(s0+s1)/2``，因为阻力是 ``1/s`` 的积分、小面积那一段占比更重
    —— ``s0=0.1, s1=1.0`` 时等效面积约 ``0.3909``，而算术平均是 ``0.55``、
    几何平均是 ``0.316``。

    推导
    ----
    令 ``ξ = dL'/L``，则 ``s(ξ) = s0 + (s1 - s0)·ξ``、``dL' = L·dξ``，于是::

        ∫₀ᴸ dL'/s = L·∫₀¹ dξ / [s0 + (s1 - s0)ξ] = L·ln(s1/s0) / (s1 - s0)

    由此 ``s_eq = (s1 - s0) / ln(s1/s0)`` —— 即**解析解**，本函数直接按它计算。

    Args:
        s0 (float): 一端的流通面积，**必须大于 0**。``s1`` 可以小于 ``s0``
            （面积沿程收缩），结果与先后顺序无关 —— 仅在浮点末位可能有差异
            （相对差约 1e-16，来自 ``s1/s0`` 与 ``s0/s1`` 的舍入不对称）。
        s1 (float): 另一端的流通面积，**必须大于 0**。

    Returns:
        float: 等效面积，即 ``(s1 - s0) / ln(s1/s0)``。

            - 任一参数 ``<= 0`` 时返回 ``0.0``（不抛异常）；
            - ``s0 == s1`` 时直接返回 ``s0``（等截面，避免 ``0/0``）。

    Note:
        两端面积相差悬殊时也**没有误差**（解析式，不再是分段数值积分）。
        此前版本用固定 100 段的中点法近似，``s1/s0`` 超过 100 时相对误差可达
        8e-3 以上（比值 1e6 时甚至约 110%）；现改为解析式后该问题消失。

    ⚠️ 传入非数值会抛 ``TypeError``（``<=`` 比较失败），本函数不做类型校验。

    Example:
        >>> equivalent_area(0.1, 1.0)
        0.39086503371292664
        >>> equivalent_area(1.0, 1.0)      # 等截面：直接返回该面积
        1.0
        >>> equivalent_area(0.0, 1.0)
        0.0
    """
    if s0 <= 0 or s1 <= 0:
        return 0.0
    if s0 == s1:  # 等截面：避免 0/0，直接返回该面积
        return float(s0)
    return (s1 - s0) / math.log(s1 / s0)


def get_average_area(s1, l1, s2, l2):
    """两段**串联**通道的流体阻力等效面积（按长度加权的调和平均）.

    把通道沿程分成两段：面积分别为 ``s1`` / ``s2``、长度分别为 ``l1`` / ``l2``。
    在 ``dp = dL / s``（阻力与流通面积成反比）的前提下，两段的阻力**相加**::

        dp_总 = l1 / s1 + l2 / s2,    L_总 = l1 + l2

    再求一个恒定面积 ``s_eq``，使它在总长上的阻力与上面相同::

        L_总 / s_eq = dp_总    =>    s_eq = (l1 + l2) / (l1/s1 + l2/s2)

    这等于以长度为权的**调和平均**：两段等长时就是 ``2 / (1/s1 + 1/s2)``。
    因为阻力是 ``1/s`` 的线性叠加，**小面积那一段占比更重**。

    与 :func:`equivalent_area` 的区别
    ---------------------------------

    ==================  ====================================  ==================
    函数                  假设                                  结果
    ==================  ====================================  ==================
    ``get_average_area``  两段**常量**面积，长度各为 l1 / l2      长度加权调和平均
    ``equivalent_area``   一段**连续线性**变截面 s0 → s1          对数平均
    ==================  ====================================  ==================

    ⚠️ 两者数值**不相等**，不该互相替代：``get_average_area(0.1, 1, 1.0, 1)`` 得
    ``0.1818``，而 ``equivalent_area(0.1, 1.0)`` 得 ``0.3909``。前者把每段的面积
    视为恒定、阻力集中在段内，结果更保守。

    Args:
        s1 (float): 第一段的流通面积。``<= 0`` 时直接返回 ``0.0``。
        l1 (float): 第一段的长度，**必须 >= 0**；为负抛 ``ValueError``。
        s2 (float): 第二段的流通面积。``<= 0`` 时直接返回 ``0.0``。
        l2 (float): 第二段的长度，**必须 >= 0**；为负抛 ``ValueError``。

    Returns:
        float: 等效面积 ``(l1 + l2) / (l1/s1 + l2/s2)``。

            - 任一面积 ``<= 0`` → 返回 ``0.0``（此时**不检查**长度，负数也照样返回）；
            - ``l2 == 0`` → 等于 ``s1``（只剩第一段）；``l1 == 0`` 时等于 ``s2``。

    Raises:
        ValueError: 以下两种情况**都**抛 ``ValueError``（同属「参数无法确定等效面积」）：

            1. ``l1 < 0`` 或 ``l2 < 0`` —— 消息形如 ``l1=-1, l2=1``；
            2. ``l1 + l2 == 0``（两段长度**都为 0**）—— 通道没有长度，等效面积无定义，
               直接报错，而**不再**让 ``dl / dp`` 抛 ``ZeroDivisionError``；
               消息形如 ``两段长度之和必须大于 0，当前 l1=0, l2=0``。

    ⚠️ 检查顺序：先判面积、再判长度、最后判总长。所以 ``get_average_area(0, -1, 1, 1)``
    返回 ``0.0`` 而**不会**抛 ``ValueError``（面积已是 0，长度怎么错都不影响结果）。

    Example:
        >>> get_average_area(0.1, 1.0, 1.0, 1.0)      # 两段等长 -> 调和平均
        0.18181818181818182
        >>> get_average_area(2.0, 5.0, 9.0, 0)        # 只剩第一段
        2.0
        >>> get_average_area(0.0, 1.0, 1.0, 1.0)      # 面积非法
        0.0
        >>> get_average_area(2.0, 3.0, 5.0, 7.0)
        3.4482758620689657
        >>> get_average_area(2.0, 0.0, 3.0, 0.0)      # 总长为 0 -> ValueError
        Traceback (most recent call last):
            ...
        ValueError: 两段长度之和必须大于 0，当前 l1=0.0, l2=0.0
    """
    if s1 <= 0 or s2 <= 0:
        return 0.0

    if l1 < 0 or l2 < 0:
        raise ValueError(f"l1={l1}, l2={l2}")

    dp = l1 / s1 + l2 / s2
    dl = l1 + l2
    if dl <= 0:  # 总长为 0：等效面积没有定义（且 dl/dp 会是 0/0）
        raise ValueError(f"两段长度之和必须大于 0，当前 l1={l1}, l2={l2}")
    return dl / dp


