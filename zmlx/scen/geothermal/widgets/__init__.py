"""地热场景的**控件集**：每个文件一个控件，供 ``zml_plugin.py`` 打开成标签页.

⚠️ **本包不导出任何东西**（与 ``zmlx.scen`` 的约定一致）：这里只有一段说明，
控件要按子模块路径导入，例如::

    from zmlx.scen.geothermal.widgets.well_cross_section import WellCrossSectionWidget

为什么控件放在这里
------------------

按 ``ui/plugins/AGENTS.md`` §1，「装配代码 + 实现都属于某个可关掉的功能」时，
二者就该放在一起 —— 地热插件关掉时，这些控件也一起关掉，``ui/`` 里不留残留。
所以控件没有放进 ``zmlx/ui/widgets/`` 或 ``zmlx/ui/tabs/``。

控件与算例的关系
----------------

控件**只负责收集参数并起任务**，不复制任何物理逻辑：建模 / 求解 / 绘图一律调用
``_well_cross_section`` 与 ``_show``，与 ``cases/`` 下是同一套实现。
所以同一套算法既能从命令行跑（``python -m ...cases.case_02``），也能从界面点出来。

现有控件
--------

=============================  ==========================================================
文件                             控件
=============================  ==========================================================
``well_cross_section.py``      ``WellCrossSectionWidget``：井截面取热的参数界面
                               （菜单「地热 → 井截面取热」）
``well_cross_section_sketch.py``  ``WellCrossSectionSketch``：x–z 剖面示意图，
                               给上面的参数界面用（不单独挂菜单）
=============================  ==========================================================

新增控件时的约定
----------------

- **一个文件一个控件**，文件名用``snake_case``，类名用``PascalCase``；
- 控件应提供 ``CAPTION`` 常量（作为标签页标题）与 ``console_exec()``
  （让「操作 → 运行」也能触发它）；
- 建模 / 求解一律调用 ``_well_cross_section``，不要在控件里重写物理逻辑；
- 在 ``zml_plugin.py`` 里用 ``gui.get_widget`` 打开，并写 ``gui_restore``
  以便重启后自动恢复（命令名一旦发布不能改）。
"""
