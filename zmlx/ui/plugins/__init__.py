"""
GUI 的插件机制：**发现、记录状态、执行**插件脚本。

⚠️ 本模块文档只讲**机制**（有哪些 API、状态存在哪、执行语义）。**插件体系的目标与本质**
（为什么不改 ``MainWindow``、什么算合法插件、为什么必须走 ``gui.xxx``、加载期为什么不能
干重活），以及**加插件 / 改内置插件**的操作规范（六步流程、三份文档的分工、常见坑、
验收命令），见同目录的 ``AGENTS.md``（§0 是总纲）。

写一个 ``zml_plugin.py`` 放在任意搜索路径下，界面启动时会自动执行它，
用于注册菜单项、添加面板、调整默认参数等。最小的插件就是几句普通代码：

.. code-block:: python

    # zml_plugin.py
    from zmlx.ui import gui

    gui.add_action(menu='帮助', name='my_note', text='我的备忘',
                   slot=lambda: gui.information('备忘', '随便写点什么'))

公共 API（只有 11 个）
----------------------

==============================  =============================================
接口                             作用
==============================  =============================================
``get_files()``                 **全部**插件的路径列表（含禁用、含文件已不存在）
``get_priority(path)``          读优先级
``set_priority(path, level)``   改优先级（``'high'`` / ``'normal'`` / ``'low'``）
``is_disabled(path)``           读「是否禁用」
``set_disabled(path, flag)``    改「是否禁用」
``add_file(path)``              手动登记一个插件文件
``remove_file(path)``           把插件移出名单（**不删磁盘文件**）
``is_standard(path)``           这个文件是自动发现的、还是用户手动登记的
``is_loaded(path)``             **本次运行**是否已经执行过（启动时执行过也算）
``load_now(path)``              立即执行（临时加载）：不改名单、不写盘、只跑一次
``get_load_error(path)``        上一次临时加载失败的原因
==============================  =============================================

⚠️ **列表只给路径，状态单独查**：``get_files()`` 不预过滤禁用 —— 要不要执行由
调用方用 ``is_disabled(path)`` 判断（``run_setup`` 就是这么做的）。这样界面也用
同一个列表画「全部插件」：某个插件被勾掉后仍然留在列表里，还能再勾回来。

外加三个执行入口：``run_setup()``（启动时执行，由 ``main.py`` 调）、
``rescan()``（重新扫描、把新出现的 ``zml_plugin.py`` 并入名单）、
``load_now(path)``（界面上的「临时加载」按钮：**当场**跑一个插件，不重启、不写盘）。

⚠️ ``is_loaded`` / ``load_now`` / ``get_load_error`` 是**运行时**状态（进程级、不落盘），
与 ``is_disabled``（持久设置）刻意分开：临时加载过的插件，重启后是否执行仍只看「启用」勾选。

⚠️ **没有「排序」接口**：用户控制的是「启用与否」与「优先级」，不排顺序。
列表顺序 = 用户登记的（按加入先后）在前、自动发现的在后，这一顺序**不对外调整**。

三个概念，各管一件事
--------------------

================  ============================  ================================
概念               用什么表达                     改它会发生什么
================  ============================  ================================
**名单**           ``zml_plugins``（有序名单）     有哪些插件（用户登记 + 自动发现）
**优先级**         ``high`` / ``normal`` / ``low``  哪些**整体**提前执行
**禁用**           ``disabled`` 标记              启动时**不执行**这段代码
================  ============================  ================================

⚠️ 「禁用」的语义只有一条：**这段代码不执行**。插件执行后派生的东西（菜单项、
后台线程）归插件自己负责，本系统不追踪、也不回收 —— 所以改了启用状态要**重启**
才看得出效果（界面「状态」列也这么写）。

⚠️ 优先级**不改变列表顺序**，只把「高」那一档整体提前、把「低」那一档整体后置；
档内仍按名单顺序。用法像调线程优先级：调它**不改变**它是什么时候被创建的。

名单从哪来
----------

1. **名单本身**（``zml_plugins``）—— 唯一真相，用户登记的与自动发现的都在这里；
2. **自动发现**（只在首次启动扫一次）—— ``app_data.get_paths()`` 与
   ``zmlx.scen`` 下每个目录**一层子目录**里的 ``zml_plugin.py``；发现到的会并入
   名单并记上 ``*``，下次启动不再扫描。要重新扫描：``rescan()``。
   ⚠️ **系统临时目录（``%TEMP%``）及 zmlx 自己的 temp 一律排除**：那里全是短命
   文件，不该当插件来源；不排除的话，``get_paths()`` + ``sys.path`` 会让临时目录
   出现两次，再展开一层子目录就是几千个候选，任何程序往那里丢一个
   ``zml_plugin.py`` 都会被当成插件**执行**并永久留在名单里（2026-10-18 修）；
3. **本包 ``builtin/`` 子目录下的 ``.py``** —— 随 zmlx 分发的**内置插件**。只需在那里
   新建一个文件，**不必**改 ``main.py`` 或 ``extra_setups/__init__.py``。⚠️ **目录即
   语义**（2026-10-19 起）：``builtin/`` 里除 ``__init__.py`` 外**每个** ``.py`` 都是
   插件、都会被启动时执行，所以**不要**往那里放工具模块或临时脚本 —— 工具放本包目录
   并以 ``_`` 开头（``_`` 是「内部实现」的既有约定，与执行判据无关）。现有的 12 个：
   ``image_browser.py``（文件 → 图片浏览）、``style_sheet_menu.py``（设置 → 样式表）、
   ``fractal_demo.py``（演示 → 经典分形；控件本体与挂载点同一个文件）等；**完整清单**见 ``ui/ReadMe.md`` 的
   ``plugins/`` 一行（12 个，其中多数声明了 ``# ** enabled = False``）。

⚠️⚠️ **插件与 ``extra_setups/`` 的分工**（2026-10-18 厘清）：

=============================  ==================================  ==============
放哪                            收什么                              用户能关掉吗
=============================  ==================================  ==============
``extra_setups/``（装配层）      **产品功能**：授权查询、用户管理        ❌ 不能
``plugins/``（本包）             **可关闭的非核心功能**：工具、彩蛋      ✅ 能
=============================  ==================================  ==============

判据：**关掉它，软件还能不能正常用？** 能 → 插件；不能 → 留在 ``extra_setups``。
把「授权查询」做成插件，等于允许用户把产品功能关掉，那是错的。

⚠️⚠️ **插件文件必须在顶层自己调注册函数**（例如文件末尾直接写 ``setup_ui()``）：
它由 ``run_setup`` **exec** 执行，**没有人**会替它调用 —— 这与 ``extra_setups/*.py``
不同，后者由 ``extra_setups/__init__.py`` 统一调用。配合 ``@execute_once`` 重复执行
也不会重复注册。

⚠️⚠️ **每个插件跑在自己的独立命名空间里**（不共用 ``app_data.space``），
**没有例外、也没有开关**：

- 插件体里的模块级定义（常量、类、辅助函数）会写进**自己的** dict，不会污染
  ``app_data.space``，也不会与别的插件**互相覆盖** —— 实测两个游戏的模块级名字
  共有 16 个（``BASE_W`` / ``CAPTION`` / ``FPS`` / ``setup_ui`` …），共用空间时
  后跑的会把先跑的值覆盖掉；
- 命名空间只给 ``__name__`` / ``__file__`` 两样。要什么就 **自己 import**
  （``from zmlx.system import app_data``）—— 依赖写在代码里、看得见；
- ``__name__`` 是 **``'__zml_plugin__'``**（2026-10-19 起；以前是 ``'__main__'``
  + 一个 ``'__zml_plugin__': True`` 的键）。于是**一个值就能区分两种运行方式**，
  插件不必 import 任何哨兵常量::

      if __name__ == '__zml_plugin__':
          setup_ui()      # 被 run_setup 执行：只注册
      elif __name__ == '__main__':
          test_1()        # 直接 python xxx.py：开窗口自测

  ⚠️ **老写法会静默失效**：把注册整段放在 ``if __name__ == '__main__':`` 里的
  插件（例如 ``gui.execute(main, ...)``），在新约定下那段代码**根本不执行**，
  表现为「插件启用了、菜单却没出现」且**没有报错**。所以 ``run_setup`` 会对这种
  文件发一条警告（判据见 :func:`zmlx.ui.plugins._alg._warn_legacy_entry`）：
  有顶格的 ``if __name__ == '__main__':``、且全文一次都没提到
  ``'__zml_plugin__'``。迁移办法就是把注册移到模块顶层，或按上面的两支改写。

同一个目录下还有旧名 ``zml_gui_setup.py`` 时也会被加载（仅作兼容，且会提示清理）；
``zml_plugin.py`` 与旧名同段时，旧名排在后面。

⚠️ 建议插件用 ``@execute_once`` 包住注册代码：``run_setup`` 在一次运行里可能被
调用多次，`execute_once` 让注册只发生一次。

插件应当自报名字与描述
----------------------

在插件文件顶部（**模块 docstring 之前或之后都行**）写下这两行注释，界面就会
用它们代替文件名显示：:

    # ** name = '图片浏览'
    # ** desc = '扫描工作路径下的图片，缩略图相册 + 大图预览'

解析走 :func:`zmlx.algs.code_config`（与 demo 同一套机制：所有 ``# **`` 行拼接后
``exec`` 一次，**不执行插件体**）。两项都是**可选的**：没写 ``name`` 就用文件名，
没写 ``desc`` 就显示「（无描述）」。读取由 :func:`zmlx.ui.plugins.get_meta` 完成。

注意：本包**只放机制** —— ``__init__.py`` / ``_alg.py`` / ``_registry.py`` 三个文件，
随包分发的插件在 ``builtin/`` 子目录里。2026-10-19 之前两者同目录、靠「文件名不以
``_`` 开头」区分；那条判据是**隐式**的，往这里丢一个临时脚本就会被启动时执行，
所以把插件下沉了一层：现在「是不是插件」由**所在目录**回答。
"""

from zmlx.ui.plugins._registry import (
    add_file, clear_choice, get_choice, get_priority, is_disabled, remove_file,
    set_disabled, set_priority)
from zmlx.ui.plugins._alg import (
    _set_default_enabled_resolver as _inject_resolver,
    get_files, get_load_error, get_meta, is_loaded, is_standard, load_now,
    rescan, run_setup)

# ★ 把「读插件自报默认状态」的能力交给 ``_registry``：它不能 import 本模块
#   （``_alg`` 依赖它），只能由入口在运行时注入。见 _registry.is_disabled。
_inject_resolver(get_meta)

if __name__ == '__main__':
    for _path in get_files():
        print(_path, get_meta(_path), '| disabled =', is_disabled(_path))
